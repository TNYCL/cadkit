/// RGB value of ACI `index`, exactly as in [`TABLE`] (index 7 is white).
///
/// Use [`crate::Entity::resolved_color`] for display colors; it maps the "foreground"
/// color 7 to black so drawings read on a white background.
// A u8 index can never exceed the 256-entry table.
#[allow(clippy::indexing_slicing)]
pub const fn to_rgb(index: u8) -> (u8, u8, u8) {
    TABLE[index as usize]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn standard_colors() {
        assert_eq!(to_rgb(1), (255, 0, 0));
        assert_eq!(to_rgb(2), (255, 255, 0));
        assert_eq!(to_rgb(3), (0, 255, 0));
        assert_eq!(to_rgb(4), (0, 255, 255));
        assert_eq!(to_rgb(5), (0, 0, 255));
        assert_eq!(to_rgb(6), (255, 0, 255));
        assert_eq!(to_rgb(7), (255, 255, 255));
        assert_eq!(to_rgb(8), (128, 128, 128));
        assert_eq!(to_rgb(9), (192, 192, 192));
        assert_eq!(to_rgb(10), (255, 0, 0));
        assert_eq!(to_rgb(255), (255, 255, 255));
    }

    /// Tier pattern of 10..=249: hue group `g = (i-10)/10` (15 degree steps), tier from the
    /// position in the group (even: 255/165/127/76/38 of the pure hue; odd: halfway to grey).
    /// Entries listed in KNOWN_DEVIATIONS differ by more than 1 in both ezdxf and ACadSharp
    /// (AutoCAD's own table is irregular there), so they are pinned instead of derived.
    #[test]
    fn tier_pattern() {
        const KNOWN_DEVIATIONS: &[usize] = &[
            109, 119, 129, 139, 147, 149, 157, 159, 167, 169, 177, 179, 187, 189, 197, 199, 209,
            219, 229, 239, 249,
        ];
        let tiers = [255.0_f64, 165.0, 127.0, 76.0, 38.0];
        for i in 10..=249usize {
            let (g, p) = ((i - 10) / 10, (i - 10) % 10);
            let k = tiers[p / 2];
            let h = g as f64 * 15.0;
            let x = (h % 60.0) / 60.0;
            let (m, n) = ((255.0 * x).floor(), (255.0 * (1.0 - x)).floor());
            let hue = match (h / 60.0) as u32 {
                0 => [255.0, m, 0.0],
                1 => [n, 255.0, 0.0],
                2 => [0.0, 255.0, m],
                3 => [0.0, n, 255.0],
                4 => [m, 0.0, 255.0],
                _ => [255.0, 0.0, n],
            };
            let even = hue.map(|c| (c * k / 255.0 + 0.5).floor());
            let want = if p % 2 == 0 {
                even
            } else {
                even.map(|c| ((c + k) / 2.0).floor())
            };
            let (r, gg, b) = to_rgb(i as u8);
            let got = [f64::from(r), f64::from(gg), f64::from(b)];
            let off = got
                .iter()
                .zip(want.iter())
                .any(|(a, b)| (a - b).abs() > 1.0);
            assert_eq!(
                off,
                KNOWN_DEVIATIONS.contains(&i),
                "index {i}: got {got:?}, pattern {want:?}"
            );
        }
    }

    #[test]
    fn table_has_256_entries() {
        assert_eq!(TABLE.len(), 256);
    }
}
