//! Text helpers shared by the DXF, DWG, and DGN readers: MTEXT format-code stripping,
//! `\U+XXXX` / `\M+nXXXX` escape decoding, and legacy DOS/OEM single-byte code pages that
//! `encoding_rs` (WHATWG) does not include. Panic-free; output size is bounded by the input.

/// Legacy DOS/OEM single-byte code pages used in pre-Unicode DWG (`$DWGCODEPAGE`), DXF, and
/// DGN drawings that have no WHATWG `encoding_rs` equivalent (`DOS866` / `ibm866` is in WHATWG).
///
/// High-half (`0x80..=0xFF`) mappings come from the Unicode Consortium Public Mapping tables
/// (`PUBLIC/MAPPINGS/VENDORS/MICSFT/PC/`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[allow(missing_docs)]
pub enum OemCodepage {
    Cp437,
    Cp850,
    Cp852,
    Cp855,
    Cp857,
    Cp860,
    Cp861,
    Cp863,
    Cp864,
    Cp865,
    Cp869,
}

impl OemCodepage {
    /// Resolves a DOS/OEM code page number (`437`, `850`, `852`, `855`, `857`, `860`, `861`,
    /// `863`, `864`, `865`, `869`).
    pub fn from_number(cp: u16) -> Option<Self> {
        Some(match cp {
            437 => Self::Cp437,
            850 => Self::Cp850,
            852 => Self::Cp852,
            855 => Self::Cp855,
            857 => Self::Cp857,
            860 => Self::Cp860,
            861 => Self::Cp861,
            863 => Self::Cp863,
            864 => Self::Cp864,
            865 => Self::Cp865,
            869 => Self::Cp869,
            _ => return None,
        })
    }

    /// Resolves a label such as `"DOS857"`, `"CP857"`, `"IBM857"`, or `"857"` (case-insensitive).
    pub fn from_label(label: &str) -> Option<Self> {
        let s = label.trim();
        let rest = if s.len() >= 3
            && s.get(..3).is_some_and(|p| {
                p.eq_ignore_ascii_case("dos")
                    || p.eq_ignore_ascii_case("ibm")
                    || p.eq_ignore_ascii_case("oem")
            }) {
            s.get(3..)?.trim_start_matches(['-', '_'])
        } else if s.len() >= 2 && s.get(..2).is_some_and(|p| p.eq_ignore_ascii_case("cp")) {
            s.get(2..)?.trim_start_matches(['-', '_'])
        } else {
            s
        };
        rest.parse::<u16>().ok().and_then(Self::from_number)
    }

    /// Canonical lowercase name (e.g. `"cp857"`).
    pub fn name(self) -> &'static str {
        match self {
            Self::Cp437 => "cp437",
            Self::Cp850 => "cp850",
            Self::Cp852 => "cp852",
            Self::Cp855 => "cp855",
            Self::Cp857 => "cp857",
            Self::Cp860 => "cp860",
            Self::Cp861 => "cp861",
            Self::Cp863 => "cp863",
            Self::Cp864 => "cp864",
            Self::Cp865 => "cp865",
            Self::Cp869 => "cp869",
        }
    }

    /// Canonical DXF `$DWGCODEPAGE` name (e.g. `"DOS857"`).
    pub fn dxf_name(self) -> &'static str {
        match self {
            Self::Cp437 => "DOS437",
            Self::Cp850 => "DOS850",
            Self::Cp852 => "DOS852",
            Self::Cp855 => "DOS855",
            Self::Cp857 => "DOS857",
            Self::Cp860 => "DOS860",
            Self::Cp861 => "DOS861",
            Self::Cp863 => "DOS863",
            Self::Cp864 => "DOS864",
            Self::Cp865 => "DOS865",
            Self::Cp869 => "DOS869",
        }
    }

    /// Encodes a Unicode character into this single-byte OEM code page when representable.
    pub fn encode_char(self, ch: char) -> Option<u8> {
        if ch.is_ascii() {
            return Some(ch as u8);
        }
        if ch == '\u{FFFD}' {
            return None;
        }
        let code = u16::try_from(u32::from(ch)).ok()?;
        self.table()
            .iter()
            .position(|&entry| entry == code)
            .map(|idx| (idx as u8) + 0x80)
    }

    fn table(self) -> &'static [u16; 128] {
        match self {
            Self::Cp437 => &CP437,
            Self::Cp850 => &CP850,
            Self::Cp852 => &CP852,
            Self::Cp855 => &CP855,
            Self::Cp857 => &CP857,
            Self::Cp860 => &CP860,
            Self::Cp861 => &CP861,
            Self::Cp863 => &CP863,
            Self::Cp864 => &CP864,
            Self::Cp865 => &CP865,
            Self::Cp869 => &CP869,
        }
    }

    /// Decodes a single 8-bit byte (`0x00..=0x7F` as ASCII, `0x80..=0xFF` via the OEM table).
    pub fn decode_byte(self, byte: u8) -> char {
        if byte < 0x80 {
            return char::from(byte);
        }
        self.table()
            .get(usize::from(byte - 0x80))
            .copied()
            .and_then(|u| char::from_u32(u32::from(u)))
            .unwrap_or('\u{FFFD}')
    }

    /// Decodes a byte slice into UTF-8.
    pub fn decode(self, bytes: &[u8]) -> String {
        if bytes.is_ascii() {
            return bytes.iter().map(|&b| char::from(b)).collect();
        }
        let mut out = String::with_capacity(bytes.len());
        for &b in bytes {
            out.push(self.decode_byte(b));
        }
        out
    }
}

