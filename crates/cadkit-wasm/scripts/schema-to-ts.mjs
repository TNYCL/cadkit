#!/usr/bin/env node
// Generates ts/document.d.ts, the TypeScript model of the document JSON (toJSON(), entity(),
// block(), entities()), from docs/schema/document-v1.schema.json.
//
//   node crates/cadkit-wasm/scripts/schema-to-ts.mjs          # rewrite ts/document.d.ts
//   node crates/cadkit-wasm/scripts/schema-to-ts.mjs --check  # exit 1 when it is stale
//
// Only the JSON Schema features the schema uses are handled: $ref, oneOf of objects tagged by
// a "type" const (emitted as named interfaces and a discriminated union), string enums,
// anyOf / type arrays with null, arrays, objects with properties or additionalProperties.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..", "..", "..");
const schemaPath = path.join(root, "docs", "schema", "document-v1.schema.json");
const outPath = path.join(here, "..", "ts", "document.d.ts");

const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
const defs = schema.$defs ?? {};
const out = [];

const pascal = (s) => s.split("_").map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join("");
const isTagged = (d) =>
  Array.isArray(d.oneOf) && d.oneOf.every((v) => v.type === "object" && v.properties?.type?.const !== undefined);

function doc(text, indent = "") {
  if (!text) return;
  const lines = text.split("\n");
  if (lines.length === 1) {
    out.push(`${indent}/** ${lines[0].replace(/\*\//g, "*\\/")} */`);
    return;
  }
  out.push(`${indent}/**`);
  for (const l of lines) out.push(`${indent} * ${l.replace(/\*\//g, "*\\/")}`.trimEnd());
  out.push(`${indent} */`);
}

function typeOf(s) {
  if (s.$ref) return s.$ref.replace("#/$defs/", "");
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((e) => JSON.stringify(e)).join(" | ");
  if (s.anyOf) return [...new Set(s.anyOf.map(typeOf))].join(" | ");
  if (s.oneOf) return [...new Set(s.oneOf.map(typeOf))].join(" | ");
  const types = Array.isArray(s.type) ? s.type : [s.type];
  const parts = types.map((t) => {
    switch (t) {
      case "integer":
      case "number":
        return "number";
      case "string":
        return "string";
      case "boolean":
        return "boolean";
      case "null":
        return "null";
      case "array": {
        const item = s.items ? typeOf(s.items) : "unknown";
        return /[ |]/.test(item) ? `Array<${item}>` : `${item}[]`;
      }
      case "object":
        if (s.properties) return inlineObject(s);
        if (s.additionalProperties) return `Record<string, ${typeOf(s.additionalProperties)}>`;
        return "Record<string, unknown>";
      default:
        return "unknown";
    }
  });
  return parts.join(" | ");
}

function inlineObject(s) {
  const req = new Set(s.required ?? []);
  const fields = Object.entries(s.properties).map(([k, v]) => `${k}${req.has(k) ? "" : "?"}: ${typeOf(v)}`);
  return `{ ${fields.join("; ")} }`;
}

function fields(s, indent) {
  const req = new Set(s.required ?? []);
  // The tag first, then the other fields in schema order (alphabetical).
  const entries = Object.entries(s.properties ?? {}).sort(([a], [b]) => (a === "type" ? -1 : b === "type" ? 1 : 0));
  for (const [k, v] of entries) {
    doc(v.description, indent);
    out.push(`${indent}${k}${req.has(k) ? "" : "?"}: ${typeOf(v)};`);
  }
}

function emitInterface(name, s, description, alias = false) {
  doc(description ?? s.description);
  out.push(alias ? `export type ${name} = {` : `export interface ${name} {`);
  fields(s, "  ");
  out.push(alias ? "};" : "}");
  out.push("");
}

out.push("// Generated by crates/cadkit-wasm/scripts/schema-to-ts.mjs from");
out.push("// docs/schema/document-v1.schema.json. Do not edit; run the script instead.");
out.push("");
// A type alias, not an interface: toJSON() was typed `any` before, and casts of its result to
// Record<string, unknown> must keep compiling.
emitInterface("DocumentJson", schema, schema.description, true);
for (const [name, d] of Object.entries(defs)) {
  if (isTagged(d)) {
    const members = [];
    for (const v of d.oneOf) {
      const member = `${name}${pascal(v.properties.type.const)}`;
      members.push(member);
      emitInterface(member, v);
    }
    doc(d.description);
    out.push(`export type ${name} = ${members.join(" | ")};`);
    out.push("");
  } else if (d.type === "object" && d.properties) {
    emitInterface(name, d);
  } else {
    doc(d.description);
    out.push(`export type ${name} = ${typeOf(d)};`);
    out.push("");
  }
}
const kinds = defs.EntityKind?.oneOf?.map((v) => JSON.stringify(v.properties.type.const)) ?? [];
doc("JSON `type` tag of an entity kind.");
out.push(`export type EntityKindName = ${kinds.join(" | ")};`);
out.push("");

const text = out.join("\n");
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8");
  } catch {}
  if (current !== text) {
    console.error("ts/document.d.ts is stale: run node crates/cadkit-wasm/scripts/schema-to-ts.mjs");
    process.exit(1);
  }
} else {
  writeFileSync(outPath, text);
}
