#!/usr/bin/env node
// Syncs the repository's own documentation into Starlight content (single source of truth):
// docs/*.md, CONTRIBUTING.md, CHANGELOG.md and the document JSON schema become pages under
// /docs/reference/, /docs/project/ and /changelog/ (see scripts/docs/manifest.mjs).
//
// Per file: the first H1 becomes the title (and leaves the body), the first sentence the
// description (or the manifest's), editUrl points at the GitHub source, and relative links
// are rewritten to the synced page when the target is published, otherwise to GitHub (main).
// Output directories are git-ignored. Files are rewritten only when their content changes;
// stale files are removed. Broken relative links and missing titles fail the build.

import { readFileSync, writeFileSync, mkdirSync, existsSync, statSync, readdirSync, rmSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DOCS, SCHEMA, ALIASES, GENERATED_DIRS } from '../docs/manifest.mjs';
import { extractTitle, firstSentence, rewriteLinks, makeResolver, frontmatter } from '../docs/transform.mjs';
import { schemaPage } from '../docs/schema-page.mjs';
import { SITE, REPO } from '../../src/config.ts';

const site = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const repoRoot = join(site, '..');
const contentRoot = join(site, 'src', 'content', 'docs');

const routes = new Map([...DOCS.map((d) => [d.source, d.route]), [SCHEMA.source, SCHEMA.route]]);
const exists = (path) => {
	const p = join(repoRoot, path);
	if (!existsSync(p)) return undefined;
	return statSync(p).isDirectory() ? 'dir' : 'file';
};
const errors = [];
const outputs = new Map();

for (const entry of DOCS) {
	const raw = readFileSync(join(repoRoot, entry.source), 'utf8').replace(/\r\n/g, '\n');
	let title, body;
	try {
		({ title, body } = extractTitle(raw));
	} catch (e) {
		errors.push(`${entry.source}: ${e.message}`);
		continue;
	}
	const description = entry.description ?? firstSentence(body);
	if (description.length < 50 || description.length > 160)
		errors.push(`${entry.source}: description must be 50-160 characters, got ${description.length}: "${description}"`);
	const resolve = makeResolver({ source: entry.source, repo: REPO, site: SITE, routes, aliases: ALIASES, exists, errors });
	const data = {
		title,
		description,
		editUrl: `${REPO}/edit/main/${entry.source}`,
		prev: entry.prev,
		...(entry.source === 'CHANGELOG.md' ? { tableOfContents: { minHeadingLevel: 2, maxHeadingLevel: 2 } } : {}),
	};
	outputs.set(entry.out, frontmatter(data) + rewriteLinks(body, resolve).trimEnd() + '\n');
}

{
	const schema = JSON.parse(readFileSync(join(repoRoot, SCHEMA.source), 'utf8'));
	const route = (source) => routes.get(source);
	const body = schemaPage(schema, {
		raw: SCHEMA.raw,
		source: `${REPO}/blob/main/${SCHEMA.source}`,
		sourcePath: SCHEMA.source,
		python: route('docs/python.md'),
		javascript: route('docs/wasm.md'),
		capi: route('docs/c-api.md'),
		architecture: route('docs/ARCHITECTURE.md'),
		changelog: route('CHANGELOG.md') + '#migrating-from-04',
	});
	const data = {
		title: 'Document JSON schema (v1)',
		description:
			'Field-by-field reference for the cadkit document JSON (schema_version 1): layers, blocks, models, entities and units, generated from the JSON Schema.',
		editUrl: `${REPO}/edit/main/${SCHEMA.source}`,
	};
	outputs.set(SCHEMA.out, frontmatter(data) + body.trimEnd() + '\n');
}

if (errors.length) {
	for (const e of errors) console.error('docs sync: ' + e);
	process.exit(1);
}

let written = 0;
for (const [out, text] of outputs) {
	const path = join(contentRoot, out);
	if (existsSync(path) && readFileSync(path, 'utf8') === text) continue;
	mkdirSync(dirname(path), { recursive: true });
	writeFileSync(path, text);
	written++;
}

const wanted = new Set([...outputs.keys()].map((o) => o.split('/').join(sep)));
let removed = 0;
const walk = (dir) => {
	if (!existsSync(dir)) return;
	for (const name of readdirSync(dir)) {
		const p = join(dir, name);
		if (statSync(p).isDirectory()) walk(p);
		else if (/\.mdx?$/.test(name) && !wanted.has(relative(contentRoot, p))) {
			rmSync(p);
			removed++;
		}
	}
};
for (const dir of GENERATED_DIRS) {
	const abs = join(contentRoot, dir);
	mkdirSync(abs, { recursive: true });
	const ignore = join(abs, '.gitignore');
	const ignoreText = '# Generated by scripts/prebuild.d/20-docs.mjs from the repository docs.\n*\n!.gitignore\n';
	if (!existsSync(ignore) || readFileSync(ignore, 'utf8') !== ignoreText) writeFileSync(ignore, ignoreText);
	walk(abs);
}

console.log(`docs sync: ${outputs.size} pages (${written} written, ${removed} removed)`);
